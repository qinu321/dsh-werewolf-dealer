/** 结算胜负一句话（§6）。 */
export function verdictSentence(verdict) {
  switch (verdict) {
    case 'human-single-wolf':
      return '最高票者现值为狼 —— 人类阵营获胜！';
    case 'wolf-single-human':
      return '最高票者现值为人类 —— 狼阵营获胜！';
    case 'wolf-peace-with-wolf':
      return '最高票为平安夜，且场上仍有狼 —— 狼阵营获胜！';
    case 'human-peace-no-wolf':
      return '最高票为平安夜，且场上已无狼 —— 人类阵营获胜！';
    case 'human-double':
      return '两名最高票并列淘汰，其中至少一名现值狼 —— 人类阵营获胜！';
    case 'wolf-double-human':
      return '两名最高票并列淘汰，且两人现值均为人类 —— 人类阵营失败！';
    case 'wolf-no-lynch':
      return '三方及以上最高票并列，无人被淘汰，且场上有狼 —— 狼阵营获胜！';
    case 'human-no-lynch':
      return '三方及以上最高票并列，无人被淘汰，且场上无狼 —— 人类阵营获胜！';
    default:
      return '结算完成。';
  }
}
