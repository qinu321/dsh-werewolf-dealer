/**
 * 换卡结果里"自己那一行"的补充说明（按**换到手的牌**）。
 * 规则卡：换卡只获得身份、不获得能力（换到预言家也只是普通人类、不能验卡）；换到狼则不知同伴。
 * 这里比较的角色名与引擎的 `ROLES` 取值一致（本模块刻意不 import 引擎，保持纯字符串/零依赖）。
 * @param {string} role - 换到手的牌。
 */
function swapSelfNote(role) {
  if (role === '狼') return '，你已经加入狼阵营，但你无法得知场上是否有你的同伴';
  if (role === '预言家') return '（但你没有验卡能力，只是个普通人类）';
  return '（只是个普通人类）';
}

/**
 * 换卡结果里"被换者那一行"的补充说明（阵营按它换到的牌算；被换者**一律不自知**，绝不发给它本人）。
 * @param {string} role - 被换者换到手的牌。
 */
function swapTargetNote(role) {
  return role === '狼'
    ? '，它已经自动变成狼阵营，但它自己不知道'
    : '，它已经自动变成人类阵营，但它自己不知道';
}

